use installer_core::{Answers, Locale, Restored, Start};
use rikka_backup::Configured;
use rikka_nix_edit::Document;
use rikka_nixos_layout::Module;

use crate::support::{answers, file, generated};

const SYSTEM: &str = r#"# Generated by Rikka. Rikka rewrites what it sets here when a setting changes;
# keep your own settings outside this directory.
{ ... }:
{
  networking.hostName = "old-desk";
  time.timeZone = "Europe/Paris";
  i18n.defaultLocale = "en_US.UTF-8";
  console.keyMap = "us";
  services.xserver.xkb.layout = "us";
  services.xserver.xkb.variant = "";
  services.printing.enable = true;
}
"#;

const APPS: &str = r#"# Generated by Rikka. Rikka rewrites what it sets here when a setting changes;
# keep your own settings outside this directory.
{ ... }:
{
  rikka.apps.browser.enable = false;
  rikka.apps.cut.enable = true;
}
"#;

const SETTINGS: &str = r#"# Generated by Rikka. Rikka rewrites what it sets here when a setting changes;
# keep your own settings outside this directory.
{ ... }:
{
  rikka.users.alice.settings."rikka.windows".layout = "tiling";
}
"#;

fn restored() -> Restored {
    Restored {
        modules: vec![
            Configured {
                module: Module::Apps,
                text: APPS.to_owned(),
            },
            Configured {
                module: Module::Settings,
                text: SETTINGS.to_owned(),
            },
            Configured {
                module: Module::System,
                text: SYSTEM.to_owned(),
            },
        ],
        declared_for: Some("alice".to_owned()),
        pending: Some("/run/media/usb/desk.rikka-backup".to_owned()),
        sign_ins: 2,
        preferences: 5,
    }
}

#[test]
fn prefills_answers_from_the_restored_configuration() {
    let mut answers = Answers {
        start: Start::Backup,
        username: String::new(),
        ..answers()
    };
    restored().prefill(&mut answers).unwrap();
    assert_eq!(answers.hostname, "old-desk");
    assert_eq!(answers.timezone, "Europe/Paris");
    assert_eq!(answers.locale, Locale::find("en_US.UTF-8").unwrap());
    assert_eq!(answers.keyboard.layout, "us");
    assert_eq!(answers.username, "alice");
    assert!(answers.apps.contains("cut"));
    assert!(!answers.apps.contains("browser"));
}

#[test]
fn restored_modules_keep_their_settings_under_the_installer_answers() {
    let answers = Answers {
        start: Start::Backup,
        hostname: "new-desk".to_owned(),
        username: "bob".to_owned(),
        restored: Some(restored()),
        ..answers()
    };
    let files = generated(&answers);
    let system = Document::parse(file(&files, "system.nix")).unwrap();
    assert_eq!(
        system
            .get::<String>("networking.hostName")
            .unwrap()
            .as_deref(),
        Some("new-desk")
    );
    assert_eq!(
        system.get::<bool>("services.printing.enable").unwrap(),
        Some(true)
    );
    let settings = Document::parse(file(&files, "settings.nix")).unwrap();
    assert_eq!(
        settings
            .get::<String>([
                "rikka",
                "users",
                "bob",
                "settings",
                "rikka.windows",
                "layout"
            ])
            .unwrap()
            .as_deref(),
        Some("tiling")
    );
    for name in ["system.nix", "settings.nix", "apps.nix"] {
        rikka_test_nixfmt::assert_formatted(file(&files, name));
    }
}

use rikka_nix_edit::{Document, Expr, Formals, Set};

use crate::{
    answers::Answers,
    error::Result,
    rikka::section,
    storage::{Filesystem, Swap},
};

const HEADER: &str = "\
Generated by the Rikka installer. Edit freely; `nixos-rebuild switch` reads it.
Filesystems, kernel modules and CPU microcode are in ./hardware-configuration.nix.
What Rikka sets for itself is in ./rikka, which it rewrites; leave that alone.";

pub(crate) fn render(answers: &Answers) -> Result<String> {
    let set = Set::new().bind(
        "imports",
        [
            Expr::path("./hardware-configuration.nix"),
            Expr::path("./rikka"),
        ],
    );
    let set = filesystems(set, answers);
    let set = section(set, "Network").bind("networking.networkmanager.enable", true);
    let set = users(set, answers);
    let set = ssh(set, answers);
    let set = swap(set, answers);
    let set = section(set, "Hardware").bind("hardware.enableRedistributableFirmware", true);
    let set = section(set, "State version")
        .comment("The release this was installed from. Leave it alone when upgrading.")
        .bind("system.stateVersion", &answers.release);

    let configuration = Expr::lambda(Formals::default().ellipsis(), set);
    Ok(Document::with_header(HEADER, configuration)?.to_string())
}

fn filesystems(set: Set, answers: &Answers) -> Set {
    let options = answers.filesystem.base_options();
    mount_points(answers.filesystem)
        .into_iter()
        .fold(section(set, "Filesystems"), |set, mount| {
            set.bind(
                ["fileSystems", mount, "options"],
                Expr::list(options.iter().copied()),
            )
        })
}

fn users(set: Set, answers: &Answers) -> Set {
    let full_name = answers.full_name.trim();
    let mut user = Set::new().bind("isNormalUser", true);
    if !full_name.is_empty() {
        user = user.bind("description", full_name);
    }
    let user = user
        .bind("extraGroups", ["wheel", "networkmanager"])
        .bind("hashedPasswordFile", answers.password_file());

    let mut set = section(set, "Users").bind(["users", "users", answers.username.as_str()], user);
    if answers.set_root_password {
        set = set.bind(
            "users.users.root.hashedPasswordFile",
            Answers::root_password_file(),
        );
    }
    if answers.sudo_rs {
        set = set.bind("security.sudo-rs.enable", true);
    }
    set
}

fn ssh(set: Set, answers: &Answers) -> Set {
    if !answers.openssh {
        return set;
    }
    section(set, "SSH").bind(
        "services.openssh",
        Set::new().bind("enable", true).bind(
            "settings",
            Set::new()
                .bind("PermitRootLogin", "no")
                .bind("PasswordAuthentication", answers.ssh_password_auth)
                .bind("KbdInteractiveAuthentication", false),
        ),
    )
}

fn swap(set: Set, answers: &Answers) -> Set {
    let Swap::Zram { percent } = answers.swap else {
        return set;
    };
    section(set, "Swap").bind(
        "zramSwap",
        Set::new()
            .bind("enable", true)
            .bind("algorithm", "zstd")
            .bind("memoryPercent", percent),
    )
}

fn mount_points(filesystem: Filesystem) -> Vec<&'static str> {
    match filesystem {
        Filesystem::Ext4 => vec!["/"],
        Filesystem::Btrfs => Filesystem::SUBVOLUMES
            .iter()
            .map(|(_, at)| if at.is_empty() { "/" } else { *at })
            .collect(),
    }
}

use rikka_nix_edit::{Document, Expr, Formals, Result, Set};

#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Module {
    Root,
    Apps,
    Boot,
    Desktop,
    Ime,
    Integration,
    Nix,
    Packages,
    System,
}

pub const DIRECTORY: &str = "/etc/nixos/rikka";

pub const FLAKE: &str = "/etc/nixos";

pub const HEADER: &str = "\
Generated by Rikka. Rikka rewrites what it sets here when a setting changes;
put anything of your own in ../configuration.nix instead.";

impl Module {
    pub const ALL: [Self; 8] = [
        Self::Apps,
        Self::Boot,
        Self::Desktop,
        Self::Ime,
        Self::Integration,
        Self::Nix,
        Self::Packages,
        Self::System,
    ];

    pub const EVERY: [Self; 9] = [
        Self::Root,
        Self::Apps,
        Self::Boot,
        Self::Desktop,
        Self::Ime,
        Self::Integration,
        Self::Nix,
        Self::Packages,
        Self::System,
    ];

    #[must_use]
    pub fn name(self) -> &'static str {
        match self {
            Self::Root => "root",
            Self::Apps => "apps",
            Self::Boot => "boot",
            Self::Desktop => "desktop",
            Self::Ime => "ime",
            Self::Integration => "integration",
            Self::Nix => "nix",
            Self::Packages => "packages",
            Self::System => "system",
        }
    }

    #[must_use]
    pub fn from_name(name: &str) -> Option<Self> {
        Self::EVERY.into_iter().find(|module| module.name() == name)
    }

    #[must_use]
    pub fn file_name(self) -> &'static str {
        match self {
            Self::Root => "default.nix",
            Self::Apps => "apps.nix",
            Self::Boot => "boot.nix",
            Self::Desktop => "desktop.nix",
            Self::Ime => "ime.nix",
            Self::Integration => "integration.nix",
            Self::Nix => "nix.nix",
            Self::Packages => "packages.nix",
            Self::System => "system.nix",
        }
    }

    #[must_use]
    pub fn path(self) -> String {
        format!("{DIRECTORY}/{}", self.file_name())
    }

    #[must_use]
    pub fn formals(self) -> Formals {
        let names: &[&str] = match self {
            Self::Desktop => &["config", "pkgs"],
            Self::Boot | Self::Ime | Self::Packages => &["pkgs"],
            Self::Root | Self::Apps | Self::Integration | Self::Nix | Self::System => &[],
        };
        Formals::new(names.iter().copied()).ellipsis()
    }

    pub fn document(self, body: Set) -> Result<Document> {
        match self {
            Self::Root => Document::with_header(HEADER, body),
            _ => Document::with_header(HEADER, Expr::lambda(self.formals(), body)),
        }
    }

    #[must_use]
    pub fn blank(self) -> Document {
        let body = match self {
            Self::Root => Set::new().bind(
                "imports",
                Expr::list(
                    Self::ALL
                        .iter()
                        .map(|module| Expr::path(format!("./{}", module.file_name()))),
                ),
            ),
            _ => Set::new(),
        };
        self.document(body)
            .expect("blank module uses valid identifiers")
    }
}

pub(crate) fn fft(x: &mut [f32; FFT_LEN], spectrum: &mut FftData) {
    ooura::forward(x);
    spectrum.copy_from_packed(x);
}

pub(crate) fn ifft(spectrum: &FftData, x: &mut [f32; FFT_LEN]) {
    spectrum.copy_to_packed(x);
    ooura::inverse(x);
}

pub(crate) fn zero_padded_hanning_fft(x: &[f32; FFT_LEN_BY_2], spectrum: &mut FftData) {
    let mut padded = [0.0; FFT_LEN];
    for ((out, sample), window) in padded[FFT_LEN_BY_2..].iter_mut().zip(x).zip(&HANNING_64) {
        *out = sample * window;
    }
    fft(&mut padded, spectrum);
}

pub(crate) fn padded_fft(
    x: &[f32; FFT_LEN_BY_2],
    old: &[f32; FFT_LEN_BY_2],
    spectrum: &mut FftData,
) {
    let mut padded = [0.0; FFT_LEN];
    padded[..FFT_LEN_BY_2].copy_from_slice(old);
    padded[FFT_LEN_BY_2..].copy_from_slice(x);
    fft(&mut padded, spectrum);
}

pub(crate) fn sqrt_hanning_padded_fft(
    x: &[f32; FFT_LEN_BY_2],
    old: &[f32; FFT_LEN_BY_2],
    spectrum: &mut FftData,
) {
    let mut padded = [0.0; FFT_LEN];
    for ((out, sample), window) in padded
        .iter_mut()
        .zip(old.iter().chain(x))
        .zip(&SQRT_HANNING_128)
    {
        *out = sample * window;
    }
    fft(&mut padded, spectrum);
}
